def _vars(palette: dict[str, str]) -> str:
    lines = []
    for key in sorted(palette):
        css_name = key.replace("_", "-")
        lines.append(f"  --{css_name}: {palette[key]};")
    return "\n".join(lines)


def _tokens_block() -> str:
    lines = [HEADER, "\n:root {", "  color-scheme: dark;", _vars(DARK)]
    lines.append(f"  --font-ui: {FONTS['ui']};")
    lines.append(f"  --font-mono: {FONTS['mono']};")
    for step, value in sorted(SPACE.items()):
        lines.append(f"  --sp-{step}: {value}px;")
    for name, value in sorted(RADIUS.items()):
        lines.append(f"  --r-{name}: {value}px;")
    for name, (size, leading, weight) in sorted(TYPE_SCALE.items()):
        prefix = name.replace("_", "-")
        lines.append(f"  --fs-{prefix}: {size}px;")
        lines.append(f"  --lh-{prefix}: {leading}px;")
        lines.append(f"  --fw-{prefix}: {weight};")
    for name, value in sorted(MOTION.items()):
        lines.append(f"  --motion-{name}: {value}ms;")
    # Совместимость со старыми именами переменных в index.html.
    lines += [
        "  --bg: var(--window);",
        "  --panel: var(--surface);",
        "  --panel2: var(--surface-raised);",
        "  --line: var(--separator);",
        "  --text: var(--label);",
        "  --muted: var(--label-secondary);",
        "  --accent2: var(--accent-fill);",
        "}",
        "",
        ":root[data-theme=\"light\"] {",
        "  color-scheme: light;",
        _vars(LIGHT),
        "}",
        "",
        ":root[data-theme=\"dark\"] {",
        "  color-scheme: dark;",
        _vars(DARK),
        "}",
        "",
        "@media (prefers-color-scheme: light) {",
        "  :root:not([data-theme]) {",
        "    color-scheme: light;",
        _vars(LIGHT),
        "  }",
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme]) {",
        "    color-scheme: dark;",
        _vars(DARK),
        "  }",
        "}",
    ]
    return "\n".join(lines)


def build_css() -> str:
    """Детерминированный CSS: два вызова дают байт-в-байт одинаковый результат."""
    return _tokens_block() + COMPONENTS


def main() -> int:
    css = build_css()
    for path in OUTPUTS:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(css, encoding="utf-8", newline="\n")
        print(f"written: {path} ({len(css)} chars)")
    # Спрайт иконок раздаётся панелью из static/ — держим точную копию.
    icons_src = ROOT / "theme" / "icons.svg"
    icons_dst = ROOT / "shorts-autopilot" / "app" / "static" / "icons.svg"
    icons_dst.parent.mkdir(parents=True, exist_ok=True)
    icons_dst.write_bytes(icons_src.read_bytes())
    print(f"written: {icons_dst}")
    # Тот же набор токенов → тема CustomTkinter и иконки для CTk-окна.
    from theme import generate_ctk  # noqa: PLC0415

    generate_ctk.main()
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
